"""Find, and with --fix mend, page-fit faults in a book's print PDFs: a chapter ending on one to
four lines, a heading left at a page's foot, a footnote broken over or set apart from its marker.

    python3 -I .claude/skills/page-fit/scripts/pagefit.py BOOK [--volume N] [--fix] [--rounds 5]

Run from the books repository's root. BOOK is what ./fgb takes (part of the folder name). It
builds the print PDFs with ./fgb pdf, reads its "page:" and "lulu: WARNING" lines, finds the
chapter file behind each fault (the page's text matched against the included chapters), and
prints them. With --fix it sets a chapter's letter spacing in the book's print file, the house
way (a `#[ #set text(tracking: X) #include ... ]` scope with a comment), builds again, and goes on
until every PDF is clean or the tries run out. A print file made by a script ("GENERATED BY" in
its head, as the Institutes' make_volumes.py) is not edited: the tracking to try is printed for
that script's table instead.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path.cwd()
# tracking to try in turn: a short ending is mostly pulled back (tighter), else pushed out (looser)
STEPS = {"end": ["-0.01em", "0.01em", "-0.015em", "0.015em", "-0.005em", "0.005em"],
         "other": ["-0.005em", "0.005em", "-0.01em", "0.01em", "-0.015em", "0.015em"]}
FAULTS = [
    (re.compile(r"a chapter ends on page (\d+) with (\d+) line"), "end", 0),
    (re.compile(r"a heading is left at the foot of page (\d+)"), "heading", 0),
    (re.compile(r"a footnote is broken over to page (\d+)"), "footnote", -1),
    (re.compile(r"footnote \S+ is set on page \d+, its marker on page (\d+)"), "footnote", 0),
]


def words(s):
    s = s.replace("ﬁ", "fi").replace("ﬂ", "fl").replace("ﬀ", "ff").replace("ﬃ", "ffi").replace("ﬄ", "ffl")
    s = re.sub(r"-\n(?=[a-z])", "", s)
    return re.findall(r"[a-z]+", s.lower())


def plain_typ(t):
    t = re.sub(r"(?m)^\s*//.*$", " ", t)
    t = re.sub(r"#[a-z.]+(\([^)]*\))?", " ", t)
    return " ".join(words(t.replace("\\", "")))


def build(book, volume):
    cmd = ["./fgb", "pdf", book] + (["--volume", volume] if volume else [])
    out = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    faults, cur = {}, None
    for line in (out.stdout + out.stderr).splitlines():
        m = re.match(r"typst: (\S+\.typ)$", line)
        if m:
            cur = m.group(1) if "cover" not in Path(m.group(1)).name else None
            continue
        if cur and line.startswith(("page: ", "lulu: WARNING")):
            for rx, kind, shift in FAULTS:
                f = rx.search(line)
                if f:
                    faults.setdefault(cur, []).append((kind, int(f.group(1)) + shift, line.split(": ", 1)[1]))
    if out.returncode:
        sys.exit(out.stdout[-2000:] + out.stderr[-2000:])
    return faults


def includes(print_file):
    t = (ROOT / print_file).read_text(encoding="utf-8")
    return [m.group(1) for m in re.finditer(r'#include "([^"]+\.typ)"', t)]


def chapter_of(print_file, page):
    """The included chapter file whose text is on PDF page `page`."""
    pdf = ROOT / "dist" / Path(print_file).relative_to("books").with_suffix(".pdf")
    txt = subprocess.run(["pdftotext", "-f", str(page), "-l", str(page), str(pdf), "-"],
                         capture_output=True, text=True).stdout
    w = words(txt)
    base = (ROOT / print_file).parent
    texts = {inc: plain_typ((base / inc).read_text(encoding="utf-8")) for inc in includes(print_file)
             if (base / inc).exists()}
    for n in (6, 5, 4):
        for i in range(len(w) - n):
            probe = " ".join(w[i:i + n])
            hits = [inc for inc, t in texts.items() if probe in t]
            if len(hits) == 1:
                return hits[0]
    return None


WRAP = r'#\[\n(\s*)#set text\(tracking: ([-\d.]+em)\)\n\s*#include "{inc}"\n\]'


def current(print_file, inc):
    m = re.search(WRAP.format(inc=re.escape(inc)), (ROOT / print_file).read_text(encoding="utf-8"))
    return m.group(2) if m else None


def set_tracking(print_file, inc, value, why):
    p = ROOT / print_file
    t = p.read_text(encoding="utf-8")
    rx = re.compile(WRAP.format(inc=re.escape(inc)))
    if rx.search(t):
        t = rx.sub(lambda m: m.group(0).replace(f"tracking: {m.group(2)}", f"tracking: {value}"), t, count=1)
    else:
        line = re.compile(rf'(?m)^#include "{re.escape(inc)}"\n')
        if not line.search(t):
            return False
        t = line.sub(f'// page fit: {why}; its letter spacing set so it falls well (page-fit skill)\n'
                     f'#[\n  #set text(tracking: {value})\n  #include "{inc}"\n]\n', t, count=1)
    p.write_text(t, encoding="utf-8")
    return True


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("book")
    ap.add_argument("--volume")
    ap.add_argument("--fix", action="store_true")
    ap.add_argument("--rounds", type=int, default=5)
    a = ap.parse_args()
    tried = {}
    for rnd in range(a.rounds + 1):
        faults = build(a.book, a.volume)
        if not faults:
            print("clean: no page-fit faults")
            return
        todo = []
        for pf, items in faults.items():
            for kind, page, msg in items:
                inc = chapter_of(pf, page)
                print(f"{pf}: {msg}  ->  {inc or '(chapter not found: check by hand)'}")
                if inc:
                    todo.append((pf, inc, kind, msg))
        if not a.fix or rnd == a.rounds:
            break
        changed = False
        for pf, inc, kind, msg in todo:
            if "GENERATED BY" in (ROOT / pf).read_text(encoding="utf-8")[:2000]:
                print(f"  {pf} is generated: set {inc} in its script's table (try {STEPS['end' if kind == 'end' else 'other'][0]})")
                continue
            steps = STEPS["end" if kind == "end" else "other"]
            done = tried.setdefault((pf, inc), [current(pf, inc)] if current(pf, inc) else [])
            nxt = next((s for s in steps if s not in done), None)
            if nxt is None:
                print(f"  {inc}: every spacing tried; fix by hand (see the skill)")
                continue
            done.append(nxt)
            why = {"end": "the chapter would end on a few lines alone", "heading": "a heading fell at a page's foot",
                   "footnote": "a footnote broke over a page"}[kind]
            if set_tracking(pf, inc, nxt, why):
                print(f"  try {inc}: tracking {nxt}")
                changed = True
        if not changed:
            break
    sys.exit(1)


if __name__ == "__main__":
    main()
